"""The keyring and the life cycle of the keys of an encrypted storage.

The other attack tests edit the storage; here the storage is left alone and
the KEYRING FILE, the 'encryption' section of the configuration and the
process that holds the keys are looked at. Every key is generated by this
harness for the run. A stored binlog is judged by decrypting it here: its
file key is unwrapped with a keyring (the operator's, the attacker's, a
wrong backup), the data is decrypted with AES-CTR and the events are
walked with their CRC32. That gives, for every binlog, the byte ranges each
keyring's holder can read ('segments': [start, end, who]).

A. the keyring file as an attack surface (the attacker can write the file
   or its directory, does not know the keys in it):
- 'a_kek_replaced_ctr', 'a_kek_replaced_gcm': the key bytes of the active
  KEK are replaced, its id and cipher kept. The source gets rows (into the
  open binlog and into a new one), 'fetch' runs. Nothing written after the
  edit may be readable by the holder of the attacker's key.
  'a_kek_replaced_gcm_rotated': the same for a GCM KEK that no binlog uses
  yet, to which the operator then rotates (the tag of a GCM key wrap can
  only tell on a KEK that already wrapped something).
- 'a_benign_edits': a record is added, the records are reordered; nothing
  may change. 'a_duplicate_ids': a second record with the id of the active
  KEK (before and after it) must be refused.
- 'a_cipher_changed': only the cipher name of the active KEK's record is
  overwritten in place (the key bytes are left as they are): GCM to CTR and
  to ECB (the key wrap loses its integrity), CTR to GCM and to ECB,
  AES-256 to AES-128. Refused, or nothing may become unreadable.
- 'a_file_kinds': the keyring path is a symlink (to a file, dangling, to a
  character device), a directory, a FIFO (must not hang), an unreadable
  file.
- 'a_permissions' (informational): is a keyring that anyone can read or
  write, or a keyring in a directory anyone can write, accepted without a
  word.
- 'a_in_storage': the keyring file inside the storage directory; it must
  be refused, or at least survive (not be removed as a garbage object).
- 'a_malformed': truncated, empty, huge (100 MB), deeply nested, duplicate
  JSON members, non-hex, odd-length hex, NUL bytes, wrong types, ...: every
  one with 'list' and 'fetch': no signal, no sanitizer report, no timeout,
  no key bytes of the file in the output or the log; those that cannot be
  a keyring must be refused. What is accepted is recorded (which of two
  duplicate members wins, which legacy ciphers pass).

B. KEK rotation as an operator does it:
- 'b_rotate_kek': 'encryption.kek_id' is changed to a new KEK with the old
  one kept in the keyring, then the old KEK is removed, then put back and
  the old binlogs purged, then removed again. list, the searches, fetch,
  pull (serving a client) and purge_binlogs run at every step; the result
  holds the table. All data must stay readable to the operator; a refusal
  must be clean.
- 'b_running_pull': the keyring file and the configuration are changed
  under a running 'pull' (when are they read again?), the source rotates,
  the connection to the source is killed; then pull is restarted.
- 'b_cipher_change': 'encryption.cipher' AES-128-CTR, then AES-256-CTR,
  then AES-192-CTR on the same storage.
- 'b_encryption_on': encryption is turned on for a storage that holds
  plain binlogs; what the open binlog gets afterwards and what
  'metadata.json' says (tickets 28 and 54 are the adjacent cases).

C. 'c_hygiene': a running 'pull' at log level 'trace' with a source
   password, a listener password and three KEKs. Its environment, command
   line, log, output, storage, telemetry and local settings are searched
   for the passwords, the KEK bytes and the unwrapped file keys (any hit
   fails the case). Its memory is read (/proc/<pid>/mem, by this harness,
   its parent; and a 'gcore' image when gdb is there, written into the work
   directory and deleted) at four moments and every copy of each secret is
   counted: after the first binlogs, after a client logged in and read an
   old binlog, after the open binlog was closed, after more traffic. Those
   numbers are informational: the active file key and the KEK have to be in
   memory, the rest shows what is not wiped.

D. 'd_uniqueness': 200 binlogs with a CTR KEK and 200 with a GCM KEK: file
   keys, data IVs and key-wrap IVs must be unique (a GCM KEK with a
   repeated wrap IV fails), IVs must not look like a counter, bytes and
   bits must look uniform (high and low half of the IV separately).

E. the operator restored the wrong keyring backup (right ids, other key
   bytes):
- 'e_wrong_keyring_ctr', 'e_wrong_keyring_gcm': three 'fetch' runs under
  the wrong keyring, then the right one is put back and fetch runs again.
  Counted: the bytes stored that the right keyring cannot read, whether
  any command said anything, what 'pull' then serves, and whether the data
  can be recovered (by the tools; by hand with both keyrings).
- 'e_wrong_keyring_pull': 'pull' is started under the wrong keyring on a
  good storage; mysqlbinlog and a MySQL replica ask it for the stored
  binlogs.

A JSON line per case ("case", "ok", "why" on failure, evidence), then a
summary; 'result.json' in the work directory; exit 1 if any case failed.
'--mode gtid' runs the storage in GTID (rewrite) mode. Example:

  PYTHONPATH=~/ws/qa/pylib python3 keyring_test.py \\
    --mysql-basedir ~/ws/dist/mysql-8.4.8-linux-glibc2.28-x86_64-minimal \\
    --binsrv ~/ws/percona-binlog-server-build-debug_gcc14/binlog_server \\
    --workdir ~/ws/qa/keyring --port 23700 --mode position
"""

