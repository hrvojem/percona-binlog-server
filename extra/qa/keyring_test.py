SANITIZER_MARKERS = ("AddressSanitizer", "LeakSanitizer",
                     "UndefinedBehaviorSanitizer", "runtime error:",
                     "Assertion")


def run(command: str, config: Path, *extra: str,
        timeout: float = COMMAND_TIMEOUT_SECONDS) -> dict:
    """Runs 'binlog_server <command> <config> ...' to its end."""
    binsrv = harness.BINSRV
    binsrv.log_path.unlink(missing_ok=True)
    started = time.monotonic()
    process = subprocess.Popen(
        [str(binsrv.binary), command, str(config), *extra],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        env=tamper.binsrv_environment())
    peak = [0]
    watcher = threading.Thread(target=tamper.watch_memory,
                               args=(process, peak), daemon=True)
    watcher.start()
    timed_out = False
    try:
        stdout, stderr = process.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        process.kill()
        stdout, stderr = process.communicate()
    watcher.join(timeout=5)
    log = (binsrv.log_path.read_text(errors="replace")
           if binsrv.log_path.exists() else "")
    return {"command": command, "exit": process.returncode,
            "seconds": round(time.monotonic() - started, 2),
            "timed_out": timed_out, "peak_rss_mb": peak[0],
            "stdout": stdout.decode(errors="replace"),
            "stderr": stderr.decode(errors="replace"), "log": log}


def message(result: dict) -> str:
    """What the command told the operator: the JSON answer's message, else
    the last error of the log, else the end of stderr."""
    try:
        answer = json.loads(result["stdout"])
        if isinstance(answer, dict) and answer.get("message"):
            return str(answer["message"])[:240]
        if isinstance(answer, dict) and answer.get("status"):
            return f"status {answer['status']}"
    except ValueError:
        pass
    errors = [line.split("] ", 2)[-1].strip() for line in
              result["log"].splitlines()
              if "[  error]" in line or "exception caught" in line]
    if errors:
        return errors[-1][:240]
    return result["stderr"].strip()[-240:]


def warnings(result: dict) -> list:
    return [line.split("] ", 2)[-1].strip()[:200] for line in
            result["log"].splitlines() if "[warning]" in line][:5]


def brief(result: dict) -> dict:
    out = {"exit": result["exit"], "message": message(result)}
    if warnings(result):
        out["warnings"] = warnings(result)
    return out


def abnormal(result: dict) -> "str | None":
    """A signal, a sanitizer report, a timeout, an odd exit code, absurd
    memory."""
    name = result["command"]
    if result["timed_out"]:
        return f"{name} did not finish"
    sanitizer = [marker for marker in SANITIZER_MARKERS
                 if marker in result["stderr"]]
    if sanitizer:
        return (f"{name} (exit {result['exit']}) printed a "
                f"{'/'.join(sanitizer)} report: "
                f"{result['stderr'].strip()[-300:]}")
    if result["exit"] < 0:
        return (f"{name} died on signal "
                f"{signal.Signals(-result['exit']).name}: "
                f"{result['stderr'].strip()[-200:]}")
    if result["exit"] not in (0, 1):
        return f"{name} exited with {result['exit']}"
    if result["peak_rss_mb"] > RSS_LIMIT_MB:
        return f"{name} used {result['peak_rss_mb']} MB"
    return None


def must_pass(result: dict, what: str) -> dict:
    if result["exit"] != 0 or abnormal(result):
        raise harness.Failure(f"{what}: {result['command']} exited with "
                              f"{result['exit']}: {message(result)}")
    return result


def output_text(result: dict) -> str:
    return result["stdout"] + result["stderr"] + result["log"]


def start_pull(config: Path, port: int, preexec=None) -> subprocess.Popen:
    binsrv = harness.BINSRV
    binsrv.log_path.unlink(missing_ok=True)
    stderr = (binsrv.workdir / "pull.stderr").open("wb")
    pull = subprocess.Popen([str(binsrv.binary), "pull", str(config)],
                            stdout=subprocess.DEVNULL, stderr=stderr,
                            env=tamper.binsrv_environment(),
                            preexec_fn=preexec)
    stderr.close()
    deadline = time.monotonic() + 40
    while time.monotonic() < deadline and pull.poll() is None:
        try:
            socket.create_connection(("127.0.0.1", port), timeout=1).close()
            return pull
        except OSError:
            time.sleep(0.1)
    if pull.poll() is None:
        pull.kill()
        pull.wait()
        raise harness.Failure("pull did not start listening in 40 s")
    return pull


def stop_pull(pull: "subprocess.Popen | None") -> "int | str | None":
    """How pull ended: its exit code, or 'killed' if SIGTERM was not
    enough."""
    if pull is None:
        return None
    if pull.poll() is None:
        pull.send_signal(signal.SIGTERM)
        try:
            pull.wait(timeout=20)
        except subprocess.TimeoutExpired:
            pull.kill()
            pull.wait()
            return "killed"
    return pull.returncode


def pull_log_errors() -> list:
    binsrv = harness.BINSRV
    if not binsrv.log_path.exists():
        return []
    return [line.split("] ", 2)[-1].strip()[:220] for line in
            binsrv.log_path.read_text(errors="replace").splitlines()
            if ("[  error]" in line or "exception caught" in line) and
            # a client closing its connection is logged as an error
            # (ticket 42)
            "system error caught in session" not in line and
            "did not reach EOF" not in line and
            # the source is stopped while a storage is only served
            "unable to establish connection" not in line][-4:]


def dump(port: int, first_binlog: str, password: "str | None" = None,
         timeout: int = 30) -> dict:
    """What a client gets of the binlogs from 'first_binlog' on:
    mysqlbinlog --raw against the listener of a running pull."""
    directory = harness.BINSRV.workdir / "dump"
    shutil.rmtree(directory, ignore_errors=True)
    directory.mkdir(parents=True)
    result = {"served": {}}
    try:
        completed = subprocess.run(
            [str(MYSQLBINLOG), "--no-defaults", "--read-from-remote-server",
             "--host=127.0.0.1", f"--port={port}",
             f"--user={tamper.PULL_USER}",
             f"--password={password or tamper.PULL_PASSWORD}",
             "--default-auth=caching_sha2_password",
             "--get-server-public-key", "--ssl-mode=DISABLED", "--raw",
             "--to-last-log", f"--result-file={directory}/", first_binlog],
            capture_output=True, timeout=timeout, check=False)
        result["exit"] = completed.returncode
        result["error"] = "; ".join(
            line for line in completed.stderr.decode(
                errors="replace").splitlines()
            if "[Warning]" not in line)[-300:]
    except subprocess.TimeoutExpired:
        result["exit"] = "timeout"
        result["error"] = f"mysqlbinlog did not finish in {timeout} s"
    for path in sorted(directory.iterdir()):
        result["served"][path.name] = path.read_bytes()
    return result


def serve(config_keyring: "Path | None", encrypt: "dict | None",
          first_binlog: str) -> dict:
    """Starts pull on the storage and dumps what it serves. The source is
    stopped meanwhile so that pull adds nothing to the storage."""
    config = write_config(config_keyring, encrypt, name="binsrv-serve.json",
                          pull_port=PULL_PORT)
    result = {"served": {}, "pull_started": False}
    pull = None
    try:
        try:
            pull = start_pull(config, PULL_PORT)
        except harness.Failure as failure:
            result["pull_error"] = str(failure)
        if pull is not None and pull.poll() is None:
            result["pull_started"] = True
            result.update(dump(PULL_PORT, first_binlog))
        elif pull is not None:
            result["pull_exit"] = pull.returncode
    finally:
        ended = stop_pull(pull)
        if result["pull_started"]:
            result["pull_stop"] = ended
    result["pull_errors"] = pull_log_errors()
    return result


