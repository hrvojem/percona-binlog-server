def swap_scenario(kek_cipher: str, edit, fetches: int = 1,
                  rotate_to: "str | None" = None) -> dict:
    """An encrypted storage of the operator's keyring (two binlogs, the
    second one open); 'edit(path, operator_keys)' changes the keyring file
    and returns the records its author holds; the source gets rows into
    the open binlog and into new ones; 'fetch' runs 'fetches' times. With
    'rotate_to' the operator points 'encryption.kek_id' at that KEK of the
    keyring after the edit (a rotation)."""
    fresh()
    operator = [record(KEK, kek_cipher), record(SPARE_KEK, kek_cipher)]
    path = write_keyring(operator)
    config = write_config(path, encryption())
    rows("BEFOREONE", 30)
    rotate()
    rows("BEFORETWO", 10)
    must_pass(run("fetch", config), "the first fetch")
    before = tamper.snapshot(harness.BINSRV)
    report_before, _ = analyse({"operator": operator})
    names_before = list(report_before)
    other = edit(path, operator)
    if rotate_to is not None:
        config = write_config(path, encryption(rotate_to))
    commands = {"list": brief(run("list", config))}
    abnormal_runs = []
    fetch_exits = []
    for number in range(1, fetches + 1):
        rows(f"AFTER{number}OPEN", 12)
        rotate()
        rows(f"AFTER{number}NEXT", 12)
        result = run("fetch", config)
        commands[f"fetch_{number}"] = brief(result)
        fetch_exits.append(result["exit"])
        if abnormal(result):
            abnormal_runs.append(abnormal(result))
    after = tamper.snapshot(harness.BINSRV)
    holders = {"operator": operator}
    if other is not None:
        holders["other"] = other
    report, plains = analyse(holders)
    return {"operator": operator, "other": other, "path": path,
            "config": config, "before": before, "after": after,
            "names_before": names_before, "report": report,
            "plains": plains, "commands": commands,
            "fetch_exits": fetch_exits, "abnormal": abnormal_runs,
            "size_before": sum(len(before[name]) for name in names_before)}


def swap_numbers(scenario: dict) -> dict:
    """What was stored after the edit and who can read it."""
    report, before = scenario["report"], scenario["before"]
    total = sum(entry.get("size", 0) for entry in report.values())
    new_bytes = total - scenario["size_before"]
    operator_total = count_bytes(report, {"operator"})
    changed_old = [name for name in scenario["names_before"][:-1]
                   if scenario["after"].get(name) != before[name]]
    rewrapped = [name for name in scenario["names_before"]
                 if json.loads(before[name + ".json"]).get("encryption") !=
                 json.loads(scenario["after"].get(name + ".json", b"{}")
                            ).get("encryption")]
    return {"bytes_stored_after_the_edit": new_bytes,
            "of_them_readable_with_the_operators_keyring":
                operator_total - scenario["size_before"],
            "of_them_readable_with_the_other_keyring":
                count_bytes(report, {"other"}),
            "of_them_readable_by_nobody": count_bytes(report, {"nobody"}),
            "closed_binlogs_changed": changed_old,
            "encryption_records_changed": rewrapped,
            "binlogs": {name: {key: value for key, value in entry.items()
                               if key in ("kek_id", "wrap", "segments",
                                          "encrypted")}
                        for name, entry in report.items()}}


def case_kek_replaced(kek_cipher: str, rotated: bool = False) -> dict:
    name = ("a_kek_replaced_" + kek_cipher.rsplit("-", 1)[-1].lower() +
            ("_rotated" if rotated else ""))
    target = SPARE_KEK if rotated else KEK
    attacker_key = record(target, kek_cipher)

    def edit(path, operator):
        # the same id and cipher, the attacker's key: the hex digits of
        # the record are overwritten where they are, which needs no read
        # access and leaves the other records as they were
        text = path.read_bytes()
        old_hex = next(key["data_hex"] for key in operator
                       if key["id"] == target).encode()
        with path.open("r+b") as keyring:
            keyring.seek(text.index(old_hex))
            keyring.write(attacker_key["data_hex"].encode())
        return [attacker_key]

    scenario = swap_scenario(kek_cipher, edit,
                             rotate_to=SPARE_KEK if rotated else None)
    numbers = swap_numbers(scenario)
    attacker_reads = readable(scenario["report"], scenario["plains"],
                              {"other"})
    markers = markers_in(attacker_reads,
                         ["BEFOREONE", "BEFORETWO", "AFTER1OPEN",
                          "AFTER1NEXT"])
    result = {"case": name, "kek_cipher": kek_cipher,
              "edit": ("data_hex of a KEK that no binlog uses yet "
                       "replaced with the attacker's key; then the "
                       "operator rotates to that KEK (kek_id)" if rotated
                       else "data_hex of the active KEK replaced with the "
                       "attacker's key (same id, same cipher)"),
              "commands": scenario["commands"], **numbers,
              "rows_the_attacker_decrypts": markers,
              "abnormal": scenario["abnormal"]}
    silent = scenario["fetch_exits"] == [0]
    attacker_bytes = numbers["of_them_readable_with_the_other_keyring"]
    result["ok"] = not attacker_bytes and not scenario["abnormal"]
    if scenario["abnormal"]:
        result["why"] = "; ".join(scenario["abnormal"])
    elif attacker_bytes:
        result["why"] = (
            f"after the key bytes of KEK '{target}' ({kek_cipher}) were "
            f"replaced in the keyring file"
            f"{' and the operator rotated to it' if rotated else ''}, "
            f"fetch exited with "
            f"{scenario['fetch_exits'][0]}"
            f"{' and said nothing' if silent else ''}: "
            f"{attacker_bytes} of the {numbers['bytes_stored_after_the_edit']}"
            f" bytes it stored can be decrypted with the attacker's key and "
            f"the stored metadata (rows {sorted(markers)}), and the "
            f"operator's keyring reads "
            f"{numbers['of_them_readable_with_the_operators_keyring']} of "
            f"them. Nothing ties a KEK id to its key bytes (no key check "
            f"value in the storage)")
    return result


def case_benign_edits() -> dict:
    steps = {}
    problems = []

    def check(label, scenario):
        numbers = swap_numbers(scenario)
        steps[label] = {"commands": scenario["commands"],
                        "readable_with_the_operators_keyring":
                            numbers["of_them_readable_with_the_operators_"
                                    "keyring"],
                        "stored": numbers["bytes_stored_after_the_edit"]}
        if scenario["fetch_exits"] != [0] or scenario["abnormal"] or \
                numbers["of_them_readable_with_the_operators_keyring"] != \
                numbers["bytes_stored_after_the_edit"] or \
                not numbers["bytes_stored_after_the_edit"]:
            problems.append(f"{label}: {steps[label]}")

    def add(path, operator):
        write_keyring(operator + [record("kr_added", "AES-128-GCM")])

    def reorder(path, operator):
        write_keyring([record("kr_first", "AES-192-CTR")] +
                      list(reversed(operator)))

    check("record_added", swap_scenario("AES-256-CTR", add))
    check("records_reordered", swap_scenario("AES-256-GCM", reorder))
    result = {"case": "a_benign_edits", "steps": steps,
              "ok": not problems}
    if problems:
        result["why"] = "; ".join(problems)[:600]
    return result


