def uniqueness(records: list, label: str, problems: list) -> dict:
    def repeated(values) -> int:
        return len(values) - len(set(values))

    file_keys = [entry["file_key"] for entry in records]
    data_ivs = [entry["data_iv"] for entry in records]
    wrap_ivs = [entry["wrap_iv"] for entry in records]
    high = [iv[:8] for iv in data_ivs]
    low = [iv[8:] for iv in data_ivs]
    low_numbers = [int.from_bytes(value, "big") for value in low]
    steps = collections.Counter(
        (second - first) % (1 << 64)
        for first, second in zip(low_numbers, low_numbers[1:]))
    # the block counter of a binlog of up to 1 GiB runs over 2^26 values:
    # two binlogs with the same high half and low halves that close reuse
    # keystream only if they also share the file key
    out = {
        "binlogs": len(records),
        "all_decrypt_with_the_unwrapped_key": all(
            entry["decrypts"] for entry in records),
        "repeated_file_keys": repeated(file_keys),
        "repeated_data_ivs": repeated(data_ivs),
        "repeated_data_iv_high_halves": repeated(high),
        "repeated_data_iv_low_halves": repeated(low),
        "repeated_wrap_ivs": repeated(wrap_ivs),
        "repeated_wrapped_keys": repeated(
            [entry["wrapped"] for entry in records]),
        "wrap_iv_equals_data_iv": sum(
            1 for entry in records
            if entry["wrap_iv"] and entry["wrap_iv"][:12] ==
            entry["data_iv"][:12]),
        "wrap_iv_bytes": sorted({len(iv) for iv in wrap_ivs}),
        "tag_bytes": sorted({len(entry["tag"]) for entry in records}),
        "most_common_step_of_the_low_half": steps.most_common(1)[0][1]
        if steps else 0,
        "low_halves_within_2^32_of_the_top": sum(
            1 for value in low_numbers if value >= (1 << 64) - (1 << 32)),
        "statistics": {
            "file_keys": byte_statistics(file_keys),
            "data_iv_high_half": byte_statistics(high),
            "data_iv_low_half": byte_statistics(low),
            "wrap_ivs": byte_statistics(wrap_ivs)}}
    for what in ("repeated_file_keys", "repeated_data_ivs",
                 "repeated_data_iv_high_halves",
                 "repeated_data_iv_low_halves", "repeated_wrap_ivs",
                 "repeated_wrapped_keys", "wrap_iv_equals_data_iv"):
        if out[what]:
            problems.append(f"{label}: {what} = {out[what]}")
    if out["most_common_step_of_the_low_half"] > 1:
        problems.append(f"{label}: the low halves of consecutive data IVs "
                        f"differ by the same value "
                        f"{out['most_common_step_of_the_low_half']} times")
    for what, statistics in out["statistics"].items():
        if not looks_random(statistics):
            problems.append(f"{label}: {what} do not look uniform: "
                            f"{statistics}")
    if not out["all_decrypt_with_the_unwrapped_key"]:
        problems.append(f"{label}: a binlog does not decrypt")
    return out


