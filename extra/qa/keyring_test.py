def unwrap(kek_record: dict, envelope: dict) -> "bytes | None":
    """The file key of a binlog as the holder of 'kek_record' gets it, or
    None when that record cannot unwrap it (a GCM tag that does not match,
    an IV of another size)."""
    try:
        cipher_name = kek_record["cipher"].upper()
        key = bytes.fromhex(kek_record["data_hex"])
        data = bytes.fromhex(envelope["data_hex"])
        initial = bytes.fromhex(envelope.get("iv_hex") or "")
        tag = bytes.fromhex(envelope.get("tag_hex") or "")
        mode_name = cipher_name.rsplit("-", 1)[-1]
        if not cipher_name.startswith("AES-"):
            return None
        if mode_name == "CTR":
            mode = modes.CTR(initial)
        elif mode_name == "GCM":
            mode = modes.GCM(initial, tag)
        elif mode_name == "CBC":
            mode = modes.CBC(initial)
        elif mode_name == "ECB":
            mode = modes.ECB()
        else:
            return None
        decryptor = Cipher(algorithms.AES(key), mode).decryptor()
        return decryptor.update(data) + decryptor.finalize()
    except (ValueError, InvalidTag, KeyError, TypeError):
        return None


def decrypt(file_key: bytes, data_envelope: dict, data: bytes) -> bytes:
    decryptor = Cipher(algorithms.AES(file_key), modes.CTR(
        bytes.fromhex(data_envelope["iv_hex"]))).decryptor()
    return decryptor.update(data) + decryptor.finalize()


def walk(plain: bytes, position: int) -> int:
    """The end of the run of well-formed events (size, end of file, CRC32)
    that starts at 'position'."""
    size = len(plain)
    while position + harness.COMMON_HEADER_SIZE + 4 <= size:
        length = int.from_bytes(plain[position + 9:position + 13], "little")
        end = position + length
        if length < harness.COMMON_HEADER_SIZE + 4 or end > size:
            break
        if zlib.crc32(plain[position:end - 4]) != int.from_bytes(
                plain[end - 4:end], "little"):
            break
        position = end
    return position


def segments(plains: dict, size: int) -> list:
    """[start, end, who]: the byte ranges of a stored binlog that decrypt
    to well-formed events with the key of 'who' ('nobody' for the rest)."""
    current = next((who for who, plain in plains.items()
                    if plain[:4] == MAGIC), None)
    if current is None:
        return [[0, size, "nobody"]]
    result = []
    start, position = 0, 4
    while position < size:
        best = None
        for who in [current] + [who for who in plains if who != current]:
            end = walk(plains[who], position)
            if end > position and (best is None or end > best[1]):
                best = (who, end)
        if best is None:
            result.append([start, position, current])
            result.append([position, size, "nobody"])
            return result
        if best[0] != current:
            result.append([start, position, current])
            start, current = position, best[0]
        position = best[1]
    result.append([start, position, current])
    return result


def analyse(keyrings: dict) -> tuple:
    """(report, plains) of the storage. 'keyrings' maps a holder's name to
    the list of records that holder has; a plain binlog's holder is
    'plaintext'."""
    binsrv = harness.BINSRV
    report, plains = {}, {}
    for name in binsrv.indexed_binlogs():
        path = binsrv.storage / name
        metadata_path = binsrv.storage / (name + ".json")
        if not path.exists() or not metadata_path.exists():
            report[name] = {"missing": True}
            continue
        data = path.read_bytes()
        metadata = json.loads(metadata_path.read_text())
        entry = {"size": len(data)}
        if metadata.get("size") != len(data):
            entry["metadata_size"] = metadata.get("size")
        candidates = {}
        record_ = metadata.get("encryption")
        if record_ is None:
            entry["encrypted"] = False
            candidates["plaintext"] = data
        else:
            key_envelope = record_["file_key_envelope"]
            data_envelope = record_["file_data_envelope"]
            entry["kek_id"] = key_envelope["kek_id"]
            entry["data_cipher"] = data_envelope["cipher"]
            entry["wrap"] = ("iv+tag" if key_envelope.get("tag_hex") else
                             "iv" if key_envelope.get("iv_hex") else "bare")
            seen = set()
            for who, keys in keyrings.items():
                kek_record = next((key for key in keys if key["id"] ==
                                   key_envelope["kek_id"]), None)
                file_key = (unwrap(kek_record, key_envelope)
                            if kek_record else None)
                if file_key is None or file_key in seen or len(
                        file_key) not in (16, 24, 32):
                    continue
                seen.add(file_key)
                candidates[who] = decrypt(file_key, data_envelope, data)
            if data[:4] == MAGIC:
                candidates.setdefault("plaintext", data)
        entry["segments"] = segments(candidates, len(data))
        report[name] = entry
        plains[name] = candidates
    return report, plains


def readable(report: dict, plains: dict, who: set) -> dict:
    """{binlog: bytes} of what the holders in 'who' can read (the readable
    ranges joined)."""
    result = {}
    for name, entry in report.items():
        parts = [plains[name][holder][start:end]
                 for start, end, holder in entry.get("segments", [])
                 if holder in who]
        result[name] = b"".join(parts)
    return result


def count_bytes(report: dict, who: set, names=None) -> int:
    return sum(end - start for name, entry in report.items()
               if names is None or name in names
               for start, end, holder in entry.get("segments", [])
               if holder in who)


def markers_in(texts: dict, markers: list) -> dict:
    found = {}
    for marker in markers:
        count = sum(text.count(marker.encode()) for text in texts.values())
        if count:
            found[marker] = count
    return found


