class Table:
    """step x command -> outcome."""

    def __init__(self):
        self.rows = []
        self.problems = []

    def add(self, step: str, command: str, outcome: str, **more) -> None:
        self.rows.append({"step": step, "command": command,
                          "outcome": outcome, **more})

    def command(self, step: str, result: dict, note: str = "") -> dict:
        text = (f"exit {result['exit']}" +
                (f": {message(result)}" if result["exit"] != 0 or
                 result["command"] in ("purge_binlogs",) else "") +
                (f" ({note})" if note else ""))
        self.add(step, result["command"], text)
        if abnormal(result):
            self.problems.append(f"{step}: {abnormal(result)}")
        return result

    def queries(self, step: str, config: Path) -> list:
        results = [self.command(step, run("list", config))]
        self.rows[-1]["command"] = "list"
        result = run("search_by_timestamp", config, "2037-01-01T00:00:00")
        self.command(step, result)
        results.append(result)
        if gtid_mode():
            # the last transaction of the source: purged binlogs do not
            # matter for it
            executed = harness.SERVER.sql(
                "SELECT @@global.gtid_executed").strip().replace("\n", "")
            uuid, _, intervals = executed.partition(":")
            last = intervals.split(":")[-1].split("-")[-1]
            result = run("search_by_gtid_set", config, f"{uuid}:{last}")
            self.command(step, result)
            results.append(result)
        return results

    def served(self, step: str, keyring: Path, encrypt: dict, first: str,
               holders: dict) -> dict:
        harness.SERVER.stop()
        try:
            result = serve(keyring, encrypt, first)
        finally:
            harness.SERVER.start()
        if not result["pull_started"]:
            self.add(step, "pull + client",
                     f"pull does not start: exit {result.get('pull_exit')}"
                     f": {(result['pull_errors'] or [''])[-1]}")
            return result
        report, plains = analyse(holders)
        check = served_check(result["served"], report, plains, "operator")
        result["check"] = check
        self.add(step, "pull + client",
                 f"{check['binlogs_served']} binlog(s), "
                 f"{check['bytes_served']} bytes served to mysqlbinlog "
                 f"(exit {result.get('exit')}), "
                 f"{'all equal to the stored plaintext' if not check['differ_from_storage'] else 'DIFFERENT: ' + str(check['differ_from_storage'])}"
                 + (f"; {result.get('error')}" if result.get("error") else ""))
        if check["differ_from_storage"]:
            self.problems.append(f"{step}: pull served "
                                 f"{check['differ_from_storage']}")
        return result


def keks_of(report: dict) -> str:
    return ", ".join(f"{name[-6:]}:{entry.get('kek_id', 'plain')}"
                     f"/{entry.get('data_cipher', '-')}"
                     for name, entry in report.items())


def all_readable(table: Table, step: str, holders: dict) -> dict:
    report, _ = analyse(holders)
    total = sum(entry.get("size", 0) for entry in report.values())
    operator = count_bytes(report, {"operator", "plaintext"})
    table.add(step, "(storage)",
              f"{len(report)} binlog(s), {total} bytes, {operator} readable "
              f"with the operator's keyring; KEK of each: {keks_of(report)}")
    if operator != total:
        table.problems.append(
            f"{step}: {total - operator} bytes of the storage are not "
            f"readable with the operator's keyring: "
            f"{ {name: entry.get('segments') for name, entry in report.items()} }")
    return report


def case_rotate_kek() -> dict:
    fresh()
    table = Table()
    old, new = record(KEK), record(NEW_KEK)
    both = [old, new]
    rows("ROTATE0", 30)
    rotate()
    rows("ROTATE0B", 10)
    # 0: before the rotation
    config = write_config(write_keyring([old]), encryption(KEK))
    table.command("0 old KEK only", must_pass(run("fetch", config),
                                              "the first fetch"))
    report = all_readable(table, "0 old KEK only", {"operator": both})
    names_0 = list(report)
    open_binlog = names_0[-1]
    metadata_0 = metadata_files()
    # 1: kek_id points at the new KEK, the old one stays in the keyring
    step = "1 kek_id -> new KEK, old KEK kept"
    config = write_config(write_keyring(both), encryption(NEW_KEK))
    table.queries(step, config)
    rows("ROTATE1OPEN", 12)
    rotate()
    rows("ROTATE1NEXT", 12)
    rotate()
    rows("ROTATE1LAST", 12)
    table.command(step, run("fetch", config))
    report = all_readable(table, step, {"operator": both})
    open_keks = {entry.get("kek_id") for name, entry in report.items()
                 if name == open_binlog}
    new_names = [name for name in report if name not in names_0]
    metadata_1 = metadata_files()
    rewrapped = [name for name in names_0 if json.loads(
        metadata_0[name + ".json"]).get("encryption") != json.loads(
        metadata_1[name + ".json"]).get("encryption")]
    table.add(step, "(storage)",
              f"the binlog that was open ({open_binlog}) grew from "
              f"{len(metadata_0) and json.loads(metadata_0[open_binlog + '.json'])['size']} to "
              f"{report[open_binlog]['size']} bytes and stays under "
              f"{sorted(open_keks)}; new binlogs {new_names} are under "
              f"{sorted({report[name].get('kek_id') for name in new_names})}"
              f"; encryption records rewritten (re-wrapped): "
              f"{rewrapped or 'none'}")
    if not new_names or {report[name].get("kek_id")
                         for name in new_names} != {NEW_KEK}:
        table.problems.append(f"{step}: the new binlogs are not under the "
                              f"new KEK: {keks_of(report)}")
    table.served(step, keyring_path(), encryption(NEW_KEK), names_0[0],
                 {"operator": both})
    # 2: the old KEK is removed
    step = "2 old KEK removed from the keyring"
    config = write_config(write_keyring([new]), encryption(NEW_KEK))
    before = tamper.snapshot(harness.BINSRV)
    refusals = table.queries(step, config)
    rows("ROTATE2", 8)
    refusals.append(table.command(step, run("fetch", config)))
    first_new = new_names[0] if new_names else names_0[-1]
    refusals.append(table.command(
        step, run("purge_binlogs", config, first_new),
        f"asked to purge everything before {first_new}"))
    served = table.served(step, keyring_path(), encryption(NEW_KEK),
                          first_new, {"operator": both})
    usable = [result["command"] for result in refusals
              if result["exit"] == 0]
    changes = tamper.describe_changes(before,
                                      tamper.snapshot(harness.BINSRV))
    old_names = [name for name, entry in report.items()
                 if entry.get("kek_id") == KEK]
    table.add(step, "(storage)",
              f"commands that still work: {usable or 'none'}"
              f"{', pull' if served['pull_started'] else ''}; "
              f"{len(old_names)} of {len(report)} binlogs are under the "
              f"removed KEK; storage files changed: {changes or 'none'}")
    half_usable = not usable and not served["pull_started"]
    unclear = [message(result) for result in refusals
               if result["exit"] != 0 and KEK not in message(result)]
    # 3: the way out: the old KEK back, the old binlogs purged
    step = "3 old KEK back, binlogs under it purged"
    config = write_config(write_keyring(both), encryption(NEW_KEK))
    table.command(step, run("fetch", config))
    report = all_readable(table, step, {"operator": both})
    first_new = next((name for name, entry in report.items()
                      if entry.get("kek_id") == NEW_KEK), None)
    purge = table.command(step, run("purge_binlogs", config,
                                    first_new or "binlog.000001"))
    report = all_readable(table, step, {"operator": both})
    # 4: now the old KEK can go
    step = "4 old KEK removed again"
    config = write_config(write_keyring([new]), encryption(NEW_KEK))
    after_purge = table.queries(step, config)
    rows("ROTATE4", 8)
    after_purge.append(table.command(step, run("fetch", config)))
    report = all_readable(table, step, {"operator": [new]})
    table.served(step, keyring_path(), encryption(NEW_KEK),
                 next(iter(report)), {"operator": [new]})
    if purge["exit"] != 0 or any(result["exit"] != 0
                                 for result in after_purge):
        table.problems.append(
            "after the binlogs under the old KEK were purged and the old "
            "KEK removed, a command still fails")
    result = {"case": "b_rotate_kek", "table": table.rows,
              "open_binlog_after_kek_id_change": sorted(open_keks),
              "re_wrapped": rewrapped,
              "informational": (
                  ([f"with the old KEK removed every command refuses the "
                    f"whole storage ({len(old_names)} of its binlogs need "
                    f"it), purge_binlogs included: the old "
                    f"KEK can only be dropped after its binlogs were "
                    f"purged WITH it in the keyring (ticket 35 for the "
                    f"query commands)"] if half_usable else []) +
                  ([f"the refusal does not name the KEK id or the binlog: "
                    f"{sorted(set(unclear))[:2]}"] if unclear else []) +
                  (["no re-wrapping: a binlog keeps the KEK it was created "
                    "under, the open binlog included, so the old KEK is "
                    "needed until those binlogs are purged"]
                   if not rewrapped else [])),
              "ok": not table.problems}
    if table.problems:
        result["why"] = "; ".join(table.problems)[:900]
    return result


def storage_size() -> int:
    return sum(len(data) for name, data in
               tamper.data_files(tamper.snapshot(harness.BINSRV)).items())


def settle(more_than: int, timeout: float = 30) -> int:
    """Waits until the storage holds more than 'more_than' data bytes and
    has stopped growing."""
    deadline = time.monotonic() + timeout
    last, since = -1, time.monotonic()
    while time.monotonic() < deadline:
        size = storage_size()
        if size != last:
            last, since = size, time.monotonic()
        elif size > more_than and time.monotonic() - since > 1.5:
            return size
        time.sleep(0.2)
    return last


def case_running_pull() -> dict:
    fresh()
    table = Table()
    old, new = record(KEK), record(NEW_KEK)
    replaced = record(KEK)
    rows("RUNNING0", 20)
    path = write_keyring([old])
