def key_size(cipher: str) -> int:
    return int(cipher.split("-")[1]) // 8


def record(kek_id: str, cipher: str = "AES-256-CTR",
           key: "bytes | None" = None) -> dict:
    key = os.urandom(key_size(cipher)) if key is None else key
    return {"id": kek_id, "cipher": cipher, "data_hex": key.hex().upper()}


def fingerprint(data: bytes) -> str:
    """What the results show of a key instead of its bytes."""
    return "sha256:" + hashlib.sha256(data).hexdigest()[:10]


def keyring_path(name: str = "keyring.json") -> Path:
    return harness.BINSRV.workdir / name


def write_keyring(keys: list, name: str = "keyring.json") -> Path:
    path = keyring_path(name)
    if path.is_symlink() or path.exists():
        path.unlink()
    path.write_text(json.dumps({"version": 1, "keys": keys}, indent=2))
    return path


def encryption(kek_id: str = KEK, cipher: str = "AES-256-CTR") -> dict:
    return {"format": "generic", "kek_id": kek_id, "cipher": cipher}


def write_config(keyring: "Path | None", encrypt: "dict | None", *,
                 name: str = "binsrv-keyring-test.json", level: str = "info",
                 pull_port: "int | None" = None,
                 listener_password: "str | None" = None,
                 source: "tuple | None" = None) -> Path:
    binsrv = harness.BINSRV
    binsrv.write_config()
    config = json.loads(binsrv.config_path.read_text())
    config["logger"]["level"] = level
    if keyring is not None:
        config["keyring"] = {"uri": f"file://{keyring}"}
    if encrypt is not None:
        config["storage"]["encryption"] = dict(encrypt)
    if source is not None:
        config["connection"]["user"], config["connection"]["password"] = \
            source
    if pull_port is not None:
        # pull serves (and stores the metadata of) what it has
        # checkpointed: every event at once
        config["storage"]["checkpoint_size"] = "1"
        config["connection"]["connect_timeout"] = 2
        # an idle pull notices SIGTERM after read_timeout (ticket 43)
        config["connection"]["read_timeout"] = 5
        config["replication_source"] = {
            "port": pull_port, "server_id": 142,
            "server_uuid": "00000000-0000-0000-0000-00000000008e",
            "read_timeout": 30, "write_timeout": 30,
            "require_secure_transport": False,
            "auth_rsa_private_key": str(tamper.AUTH_RSA_PRIVATE_KEY),
            "authentication": {
                "user": tamper.PULL_USER,
                "password": listener_password or tamper.PULL_PASSWORD,
                "plugin": "caching_sha2_password"}}
    path = binsrv.workdir / name
    path.write_text(json.dumps(config, indent=2))
    return path


