    result = {"case": "a_in_storage", "steps": steps,
              "keyring_still_there": path.exists(),
              "informational": [
                  f"a keyring file inside the storage directory counts as "
                  f"a storage object: fetch refuses the storage; commands "
                  f"that ran all the same: {accepted} (the query commands "
                  f"skip what they do not know)"],
              "ok": not problems}
    if problems:
        result["why"] = "; ".join(problems)[:600]
    return result


