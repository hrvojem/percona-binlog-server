def served_check(served: dict, report: dict, plains: dict,
                 who: str) -> dict:
    """Compares what pull served with what the storage holds for 'who'."""
    reference = readable(report, plains, {who, "plaintext"})
    wrong = {}
    for name, data in served.items():
        expected = reference.get(name, b"")
        if data != expected[:len(data)] or not data:
            wrong[name] = (f"{len(data)} bytes served, the same as the "
                           f"stored plaintext up to "
                           f"{tamper.first_difference(data, expected)}")
    return {"binlogs_served": len(served),
            "bytes_served": sum(len(data) for data in served.values()),
            "differ_from_storage": wrong}


def secrets_in(text: str, needles: dict) -> list:
    """The names of the secrets found in 'text' (hex in either case)."""
    lowered = text.lower()
    return sorted(name for name, needle in needles.items()
                  if needle and needle.lower() in lowered)


