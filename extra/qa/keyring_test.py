def main():
    global ARGS, PULL_PORT, REPLICA_PORT, MYSQLBINLOG
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--mysql-basedir", type=Path, required=True)
    parser.add_argument("--binsrv", type=Path, required=True)
    parser.add_argument("--workdir", type=Path, required=True)
    parser.add_argument("--port", type=int, default=23700,
                        help="the source's port; the replica uses the next "
                             "one, the listener of 'pull' the one after")
    parser.add_argument("--mode", choices=["position", "gtid"],
                        default="position")
    parser.add_argument("--cases", nargs="*", choices=list(CASES),
                        help="the cases to run (default: all)")
    args = parser.parse_args()
    args.mysql_basedir = args.mysql_basedir.expanduser()
    args.workdir = args.workdir.expanduser().resolve()
    args.workdir.mkdir(parents=True, exist_ok=True)
    ARGS = args
    REPLICA_PORT = args.port + 1
    # the replica logs in at the listener with these
    replication.PULL_USER = tamper.PULL_USER
    replication.PULL_PASSWORD = tamper.PULL_PASSWORD
    PULL_PORT = args.port + 2
    MYSQLBINLOG = args.mysql_basedir / "bin" / "mysqlbinlog"
    gtid = args.mode == "gtid"
    harness.SERVER = harness.MySQLServer(args.mysql_basedir,
                                         args.workdir / "mysql", args.port,
                                         gtid, server_id=1)
    harness.BINSRV = harness.BinlogServer(args.binsrv.expanduser(),
                                          args.workdir / "binsrv", args.port,
                                          gtid)
    results = []
    started = time.monotonic()
    harness.SERVER.start()
    try:
        for name in args.cases or list(CASES):
            case_started = time.monotonic()
            try:
                result = CASES[name]()
            except (harness.Failure, RuntimeError, OSError, ValueError,
                    LookupError, TypeError, StopIteration,
                    subprocess.SubprocessError) as failure:
                result = {"case": name, "ok": False,
                          "why": "the case could not run: " +
                                 harness.describe_failure(failure, 600)}
                if harness.SERVER.process is None:
                    harness.SERVER.start()
            result["mode"] = args.mode
            result["seconds"] = round(time.monotonic() - case_started, 1)
            print(json.dumps(result), flush=True)
            results.append(result)
    finally:
        harness.SERVER.stop()
        # nothing of the run stays behind but the results
        for leftover in ("mysql", "replica"):
            shutil.rmtree(args.workdir / leftover, ignore_errors=True)
        shutil.rmtree(harness.BINSRV.workdir / "core", ignore_errors=True)
    failures = [result for result in results if not result.get("ok")]
    print(json.dumps({"cases": len(results), "failures": len(failures),
                      "failed": [result["case"] for result in failures],
                      "mode": args.mode,
                      "build": args.binsrv.expanduser().parent.name,
                      "seconds": round(time.monotonic() - started),
                      "passed": not failures}), flush=True)
    (args.workdir / "result.json").write_text(json.dumps(results, indent=2))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
