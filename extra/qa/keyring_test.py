PR_SET_PTRACER = 0x59616D61


def allow_ptrace() -> None:
    """Run in the child before exec: lets a debugger that is not its
    ancestor (gcore) attach under Yama's ptrace_scope 1. A setting of this
    one process."""
    try:
        ctypes.CDLL(None).prctl(PR_SET_PTRACER, ctypes.c_ulong(-1), 0, 0, 0)
    except OSError:
        pass


def region_kind(path: str) -> str:
    if path in ("[heap]", "[stack]"):
        return path
    if not path:
        return "anonymous"
    if path.startswith("["):
        return path
    return "file:" + Path(path).name[:24]


def scan_memory(pid: int, needles: dict) -> dict:
    """Every copy of each needle in the readable memory of 'pid' (a child
    of this process, stopped meanwhile): {name: {"copies", "where":
    {region kind: copies}, "addresses": [...]}}."""
    scanned = 0
    os.kill(pid, signal.SIGSTOP)
    try:
        time.sleep(0.05)
        if callable(needles):
            # what the storage holds now that the process stands still
            needles = needles()
        longest = max(len(needle) for needle in needles.values())
        found = {name: {"copies": 0, "where": collections.Counter(),
                        "addresses": []} for name in needles}
        maps = Path(f"/proc/{pid}/maps").read_text().splitlines()
        with open(f"/proc/{pid}/mem", "rb", buffering=0) as memory:
            for line in maps:
                fields = line.split(None, 5)
                start, end = (int(value, 16)
                              for value in fields[0].split("-"))
                path = fields[5].strip() if len(fields) > 5 else ""
                if "r" not in fields[1] or path in (
                        "[vvar]", "[vsyscall]", "[vvar_vclock]") or \
                        end - start > (8 << 30):
                    continue
                kind = region_kind(path)
                carry = b""
                position = start
                while position < end:
                    length = min(8 << 20, end - position)
                    try:
                        memory.seek(position)
                        chunk = memory.read(length)
                    except (OSError, ValueError, OverflowError):
                        chunk = b""
                    if not chunk:
                        carry = b""
                        position += length
                        continue
                    scanned += len(chunk)
                    data = carry + chunk
                    base = position - len(carry)
                    for name, needle in needles.items():
                        at = data.find(needle)
                        while at != -1:
                            found[name]["copies"] += 1
                            found[name]["where"][kind] += 1
                            found[name]["addresses"].append(base + at)
                            at = data.find(needle, at + 1)
                    carry = data[-(longest - 1):] if longest > 1 else b""
                    position += len(chunk)
    finally:
        os.kill(pid, signal.SIGCONT)
    for entry in found.values():
        entry["where"] = dict(entry["where"])
    found["_scanned_mb"] = scanned >> 20
    return found


def scan_file(path: Path, needles: dict) -> dict:
    longest = max(len(needle) for needle in needles.values())
    counts = {name: 0 for name in needles}
    carry = b""
    with path.open("rb") as image:
        while True:
            chunk = image.read(16 << 20)
            if not chunk:
                break
            data = carry + chunk
            for name, needle in needles.items():
                at = data.find(needle)
                while at != -1:
                    counts[name] += 1
                    at = data.find(needle, at + 1)
            carry = data[-(longest - 1):]
    return counts


def process_facts(pid: int) -> dict:
    facts = {}
    proc = Path(f"/proc/{pid}")
    try:
        facts["coredump_filter"] = (proc / "coredump_filter").read_text(
            ).strip()
        for line in (proc / "limits").read_text().splitlines():
            if line.startswith("Max core file size"):
                facts["core_file_size_limit_soft_hard"] = line.split()[4:6]
        # the files under /proc/<pid> of a process that is not dumpable
        # belong to root, and its memory cannot be opened
        facts["dumpable"] = (proc / "mem").stat().st_uid == os.getuid()
        for line in (proc / "status").read_text().splitlines():
            if line.split(":")[0] in ("VmRSS", "VmSize", "VmLck", "Threads",
                                      "NoNewPrivs", "TracerPid"):
                facts[line.split(":")[0]] = " ".join(line.split()[1:])
    except OSError as error:
        facts["error"] = str(error)
    facts["core_pattern"] = Path(
        "/proc/sys/kernel/core_pattern").read_text().strip()[:60]
    try:
        facts["ptrace_scope"] = Path(
            "/proc/sys/kernel/yama/ptrace_scope").read_text().strip()
    except OSError:
        pass
    return facts


def gcore_image(pid: int, needles: dict) -> dict:
    """A core image of 'pid' made by gcore inside the work directory,
    searched and deleted."""
    gcore = shutil.which("gcore")
    if gcore is None:
        return {"skipped": "gcore is not installed"}
    directory = harness.BINSRV.workdir / "core"
    shutil.rmtree(directory, ignore_errors=True)
    directory.mkdir(parents=True)
    result = {}
    try:
        completed = subprocess.run(
            [gcore, "-o", str(directory / "image"), str(pid)],
            capture_output=True, timeout=180, check=False,
            stdin=subprocess.DEVNULL)
        images = sorted(directory.glob("image*"))
        if completed.returncode != 0 or not images:
            result["failed"] = (completed.stderr.decode(errors="replace")
                                .strip()[-200:] or
                                f"exit {completed.returncode}")
        else:
            result["size_mb"] = images[0].stat().st_size >> 20
            result["copies"] = scan_file(images[0], needles)
    except subprocess.TimeoutExpired:
        result["failed"] = "gcore did not finish in 180 s"
    finally:
        shutil.rmtree(directory, ignore_errors=True)
    result["image_deleted"] = not directory.exists()
    return result


