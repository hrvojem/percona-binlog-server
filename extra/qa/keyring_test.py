def case_wrong_keyring(kek_cipher: str) -> dict:
    name = "e_wrong_keyring_" + kek_cipher.rsplit("-", 1)[-1].lower()
    wrong_key = record(KEK, kek_cipher)

    def edit(path, operator):
        write_keyring([wrong_key] + operator[1:])
        return [wrong_key]

    scenario = swap_scenario(kek_cipher, edit, fetches=3)
    numbers = swap_numbers(scenario)
    right, wrong = scenario["operator"], [wrong_key]
    holders = {"operator": right, "other": wrong}
    result = {"case": name, "kek_cipher": kek_cipher,
              "under_the_wrong_keyring": {
                  "commands": scenario["commands"], **numbers}}
    problems = list(scenario["abnormal"])
    lost_under_wrong = (numbers["bytes_stored_after_the_edit"] -
                        numbers["of_them_readable_with_the_operators_"
                                "keyring"])
    # the right keyring is back
    path = write_keyring(right)
    config = scenario["config"]
    back = {"list": brief(run("list", config))}
    rows("BACKOPEN", 12)
    fetched = run("fetch", config)
    back["fetch"] = brief(fetched)
    if abnormal(fetched):
        problems.append(abnormal(fetched))
    report, plains = analyse(holders)
    total = sum(entry.get("size", 0) for entry in report.values())
    right_bytes = count_bytes(report, {"operator"})
    lost_now = total - right_bytes
    first = next(iter(report))
    harness.SERVER.stop()
    try:
        served = serve(path, encryption(), first)
    finally:
        harness.SERVER.start()
    reference = readable(report, plains, {"operator"})
    garbage = {}
    for binlog, data in served["served"].items():
        good = tamper.first_difference(data, plains[binlog].get(
            "operator", b"")) if binlog in plains else 0
        stored_good = len(reference.get(binlog, b""))
        if len(data) > min(good, stored_good):
            garbage[binlog] = (f"{len(data)} bytes served, well-formed up "
                               f"to {walk(data, 4) if data[:4] == MAGIC else 0}")
    back.update({
        "bytes_in_the_storage": total,
        "readable_with_the_right_keyring": right_bytes,
        "unreadable_with_the_right_keyring": lost_now,
        "readable_by_hand_with_both_keyrings":
            count_bytes(report, {"operator", "other"}),
        "readable_by_nobody": count_bytes(report, {"nobody"}),
        "binlogs": {binlog: entry.get("segments")
                    for binlog, entry in report.items()},
        "pull": {"started": served["pull_started"],
                 "errors": served["pull_errors"],
                 "client_exit": served.get("exit"),
                 "client_error": served.get("error"),
                 "served": {binlog: len(data) for binlog, data in
                            served["served"].items()},
                 "served_beyond_the_readable_part": garbage}})
    result["right_keyring_back"] = back
    result["bytes_stored_unreadable_while_fetch_exited_0"] = (
        lost_under_wrong if 0 in scenario["fetch_exits"] else 0)
    result["fetch_exits_under_the_wrong_keyring"] = scenario["fetch_exits"]
    if lost_under_wrong and 0 in scenario["fetch_exits"]:
        problems.append(
            f"under a keyring with other key bytes for KEK '{KEK}' "
            f"({kek_cipher}) three fetch runs exited "
            f"{scenario['fetch_exits']} and stored {lost_under_wrong} of "
            f"{numbers['bytes_stored_after_the_edit']} new bytes that the "
            f"right keyring cannot read; list said "
            f"{scenario['commands']['list']['message']!r}. With the right "
            f"keyring back fetch exits {fetched['exit']} and "
            f"{lost_now} bytes stay unreadable "
            f"({back['readable_by_hand_with_both_keyrings'] - right_bytes} "
            f"of them only by hand with both keyrings, "
            f"{back['readable_by_nobody']} by nobody)")
    if garbage:
        problems.append(f"pull then serves undecryptable bytes to a "
                        f"client: {garbage}")
    result["ok"] = not problems
    if problems:
        result["why"] = "; ".join(problems)[:1100]
    return result


def case_wrong_keyring_pull() -> dict:
    steps = {}
    problems = []
    replica = harness.MySQLServer(ARGS.mysql_basedir,
                                  ARGS.workdir / "replica", REPLICA_PORT,
                                  gtid_mode(), server_id=2)
    replica.start()
    try:
        for kek_cipher in ("AES-256-CTR", "AES-256-GCM"):
            fresh()
            binsrv = harness.BINSRV
            right = [record(KEK, kek_cipher)]
            wrong = [record(KEK, kek_cipher)]
            path = write_keyring(right)
            rows("SERVEDROW", 20)
            rotate()
            rows("SERVEDROW2", 10)
            must_pass(run("fetch", write_config(path, encryption())),
                      "the first fetch")
            source_rows = int(harness.SERVER.sql(
                "SELECT COUNT(*) FROM qa.t").strip())
            names = binsrv.indexed_binlogs()
            stored = tamper.snapshot(binsrv)
            write_keyring(wrong)
            config = write_config(path, encryption(), pull_port=PULL_PORT)
            step = {}
            harness.SERVER.stop()
            pull = None
            try:
                try:
                    pull = start_pull(config, PULL_PORT)
                except harness.Failure as failure:
                    step["pull"] = str(failure)[:200]
                if pull is not None and pull.poll() is None:
                    client = dump(PULL_PORT, names[0])
                    step["mysqlbinlog"] = {
                        "exit": client["exit"], "error": client["error"],
                        "served": {
                            name: f"{len(data)} bytes, well-formed up to "
                                  f"{walk(data, 4) if data[:4] == MAGIC else 0}"
                            for name, data in client["served"].items()}}
                    step["rows_of_the_source_in_what_was_served"] = sum(
                        data.count(b"SERVEDROW")
                        for data in client["served"].values())
                    replication.replicate_from_pull(
                        replica, PULL_PORT, gtid_mode(),
                        "SOURCE_AUTO_POSITION=1" if gtid_mode() else
                        f"SOURCE_LOG_FILE='{names[0]}', SOURCE_LOG_POS=4")
                    deadline = time.monotonic() + 8
                    state = replica_tamper.replica_state(replica)
                    while time.monotonic() < deadline:
                        state = replica_tamper.replica_state(replica)
                        if state["row_count"] >= source_rows or any(
                                len(fields) > 1 and
                                fields[1] not in ("0", "")
                                for fields in (state["receiver"],
                                               state["applier"])):
                            break
                        time.sleep(1)
                    step["replica"] = {
                        "rows": state["row_count"],
                        "rows_on_the_source": source_rows,
                        "receiver": state["receiver"],
                        "applier": state["applier"]}
                    replica.sql("STOP REPLICA")
                    garbage_bytes = sum(
                        len(data) - (walk(data, 4) if data[:4] == MAGIC
                                     else 0)
                        for data in client["served"].values())
                    if garbage_bytes or (
                            client["served"] and
                            not step["rows_of_the_source_in_what_was_served"]
                            and any(client["served"].values())):
                        step["undecryptable_bytes_served"] = garbage_bytes
                        if not pull_log_errors():
                            problems.append(
                                f"{kek_cipher}: pull under a wrong keyring "
                                f"sent {garbage_bytes} bytes of wrongly "
                                f"decrypted data to a client and logged no "
                                f"error")
                elif pull is not None:
                    step["pull"] = f"exit {pull.returncode}"
            finally:
                step["pull_stop"] = stop_pull(pull)
                harness.SERVER.start()
            step["pull_errors"] = pull_log_errors()
            changes = tamper.describe_changes(stored,
                                              tamper.snapshot(binsrv))
            step["storage_changed"] = changes
            steps[kek_cipher] = step
    finally:
        replica.stop()
        shutil.rmtree(ARGS.workdir / "replica", ignore_errors=True)
    result = {"case": "e_wrong_keyring_pull", "steps": steps,
              "ok": not problems}
    if problems:
        result["why"] = "; ".join(problems)[:900]
    return result


