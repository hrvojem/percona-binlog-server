def case_malformed() -> dict:
    fresh()
    rows("MALFORMED", 5)
    binsrv = harness.BINSRV
    path = keyring_path()
    config = write_config(path, encryption())
    refused, accepted, problems = {}, {}, []
    slow = {}
    forged_lines = build_paths = 0
    for name, content, expected, secrets in malformed_variants():
        binsrv.reset()
        path.write_bytes(content)
        outcome = {}
        texts = []
        for command in ("list", "fetch"):
            result = run(command, config,
                         timeout=MALFORMED_TIMEOUT_SECONDS)
            outcome[command] = result["exit"]
            texts.append(output_text(result))
            if abnormal(result):
                problems.append(f"{name}: {abnormal(result)}")
            if result["seconds"] > 5 or result["peak_rss_mb"] > 400:
                slow[f"{name}/{command}"] = [result["seconds"],
                                             result["peak_rss_mb"]]
            outcome["message"] = message(result)[:160]
        secrets = {what: value for what, value in secrets.items()
                   if len(value) >= 16}
        leaked = secrets_in("".join(texts), secrets)
        if leaked:
            problems.append(f"{name}: {leaked} of the keyring file in the "
                            f"output or the log")
        if name == "id_with_a_log_line":
            forged_lines = sum(
                1 for text in texts for line in text.splitlines()
                if line.startswith("[2026-01-01 00:00:00.000000] [   info] "
                                   "forged line"))
        if any("/boost/" in text or ".hpp:" in text for text in texts):
            build_paths += 1
        if outcome["fetch"] == 0:
            entry = {"list": outcome["list"]}
            report, _ = analyse({
                what: [{"id": KEK, "cipher": "AES-256-CTR",
                        "data_hex": value}]
                for what, value in secrets.items() if len(value) == 64})
            holders = sorted({holder for item in report.values()
                              for _, _, holder in item.get("segments", [])})
            if name.startswith("duplicate_") or "nul" in name:
                entry["stored_binlogs_read_with"] = holders
            wraps = sorted({item.get("wrap", "plain")
                            for item in report.values()})
            if name.startswith("kek_cipher_"):
                entry["key_wrap"] = wraps
            accepted[name] = entry
            if expected == "refuse":
                problems.append(f"{name}: accepted (list exits "
                                f"{outcome['list']}, fetch exits 0)")
        else:
            refused[name] = outcome["message"]
            if expected == "accept":
                problems.append(f"{name}: refused: {outcome['message']}")
    path.write_text("{}")
    weak = sorted(name[len("kek_cipher_"):] for name in accepted
                  if name.startswith("kek_cipher_") and
                  not name.startswith(("kek_cipher_AES-256-C",
                                       "kek_cipher_ARIA",
                                       "kek_cipher_CAMELLIA")))
    result = {"case": "a_malformed", "variants": len(refused) + len(accepted),
              "refused": refused, "accepted": accepted,
              "slow_or_large": slow,
              "informational": (
                  ([f"KEK ciphers accepted besides AES / ARIA / CAMELLIA "
                    f"in CTR, CBC, GCM: {weak}"] if weak else []) +
                  ([f"a key id with a line break is written to the log as "
                    f"it is: {forged_lines} forged log line(s)"]
                   if forged_lines else []) +
                  ([f"{build_paths} refusals print the path of a Boost "
                    f"source file on the build host (boost.json error "
                    f"location)"] if build_paths else []) +
                  ["of two JSON members with the same name the last one "
                   "is used (see 'stored_binlogs_read_with')"]),
              "ok": not problems}
    if problems:
        result["why"] = "; ".join(problems)[:1200]
    return result


